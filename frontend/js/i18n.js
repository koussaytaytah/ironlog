let CURRENT_LANG = (typeof localStorage !== 'undefined' && localStorage.getItem('ironlog_lang')) || 'fr';

function setLang(lang) {
  CURRENT_LANG = ['ar','fr','en'].includes(lang) ? lang : 'fr';
  try { localStorage.setItem('ironlog_lang', CURRENT_LANG); } catch(e){}
  applyLangDir();
  if (typeof render === 'function') render();
}

function applyLangDir() {
  document.documentElement.lang = CURRENT_LANG;
  document.documentElement.dir = CURRENT_LANG === 'ar' ? 'rtl' : 'ltr';
}

function t(path) {
  const parts = path.split('.');
  let node = I18N[CURRENT_LANG];
  for (const p of parts) {
    if (node == null) break;
    node = node[p];
  }
  if (node == null) {
    // fallback to fr then en
    node = I18N.fr;
    for (const p of parts) {
      if (node == null) return path;
      node = node[p];
    }
    if (node == null) {
      node = I18N.en;
      for (const p of parts) {
        if (node == null) return path;
        node = node[p];
      }
    }
  }
  return node;
}

